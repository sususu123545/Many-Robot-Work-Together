#!/usr/bin/env python3
"""Generate the MoveIt 2 configuration package for the ArmPi Pro, by hand.

Why not MoveIt Setup Assistant
------------------------------
MSA is a Qt GUI and this robot is headless (no rviz2, no X on the car).  All it
produces is text: the SRDF, joint limits, kinematics and planner parameters.
Everything it would ask for is already known here, and some of it is known BETTER
than a wizard could guess:

  * the joint limits come from the servo ticks this project measured, not from a
    nominal datasheet;
  * the planning chain is fixed by the URDF we just validated to 0.7 mm against
    the live TF tree;
  * the self-collision exemptions are derived from the URDF's own joint list, so
    they cannot drift out of sync with the links.

The one thing MSA is genuinely good at -- clicking through a 3-D model to pick
groups -- is exactly the thing we cannot do on a headless board.

    python3 tools/build_moveit_config.py
    python3 tools/build_moveit_config.py --out /tmp/cfg
"""

import argparse
import math
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
URDF = os.path.join(REPO, 'ros2_ws', 'src', 'robot_description', 'urdf',
                    'armpi_pro.urdf')
DEFAULT_OUT = os.path.join(REPO, 'ros2_ws', 'src', 'armpi_pro_moveit_config',
                           'config')

TICK_RAD = math.radians(240.0) / 1000.0
SIGNS = {'joint1': 1.0, 'joint2': 1.0, 'joint3': -1.0, 'joint4': 1.0, 'joint5': 1.0}
ARM_JOINTS = ('joint1', 'joint2', 'joint3', 'joint4', 'joint5')

# From tools/arm_jog.py's measured servo ranges, converted to ticks.  These are
# the REAL mechanical limits, narrower than the URDF's nominal +-2.09 rad.
TICK_LIMITS = {
    'joint1': (0, 1000),
    'joint2': (125, 875),
    'joint3': (0, 1000),
    'joint4': (0, 1000),
    'joint5': (0, 1000),
}
# Rad/s at 0.24 deg per tick per second; the vendor node caps a move at 100
# ticks in one trajectory point, which is where this number comes from.
MAX_VELOCITY = 1.2
MAX_ACCELERATION = 2.0

# Startup pose actually installed on the car (car_setup/ros2/arm_startup_pose.json)
STARTUP_TICKS = {'joint1': 483, 'joint2': 686, 'joint3': 907, 'joint4': 199,
                 'joint5': 496}


def ticks_to_radians(name, tick):
    return SIGNS[name] * (float(tick) - 500.0) * TICK_RAD


def limits_radians(name):
    """(min, max) in radians, always ordered low..high.

    joint3 has a NEGATIVE sign, so its tick range 0..1000 converts to
    +2.0944 .. -2.0944 -- an inverted pair.  Emitting that straight into
    joint_limits.yaml makes min_position > max_position and MoveIt aborts every
    request with "Joint 'joint3' from the starting state is outside bounds".
    """
    low, high = TICK_LIMITS[name]
    a, b = ticks_to_radians(name, low), ticks_to_radians(name, high)
    return (min(a, b), max(a, b))


def adjacent_pairs(root):
    """Every (parent, child) link pair a joint directly connects.

    These are the pairs that must be exempt from self-collision: they touch by
    construction, so without the exemption MoveIt treats every plan as colliding
    with itself and refuses to move at all.
    """
    pairs = []
    for joint in root.findall('joint'):
        parent = joint.find('parent').get('link')
        child = joint.find('child').get('link')
        pairs.append((parent, child))
    return pairs


def build_srdf(root):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!-- Generated by tools/build_moveit_config.py -->',
             '<robot name="armpi_pro">']
    lines.append('  <group name="arm">')
    lines.append('    <chain base_link="arm_base" tip_link="grasping_frame"/>')
    lines.append('  </group>')
    lines.append('  <group name="gripper">')
    for joint in ('r_joint', 'l_joint'):
        lines.append('    <joint name="%s"/>' % joint)
    lines.append('  </group>')
    lines.append('  <group name="arm_with_gripper">')
    lines.append('    <group name="arm"/>')
    lines.append('    <group name="gripper"/>')
    lines.append('  </group>')
    lines.append('')
    lines.append('  <end_effector name="gripper_eef" parent_link="grasping_frame"'
                 ' group="gripper" parent_group="arm"/>')
    lines.append('')
    for parent, child in adjacent_pairs(root):
        lines.append('  <disable_collisions link1="%s" link2="%s" reason="Adjacent"/>'
                     % (parent, child))
    lines.append('')
    pose = ' '.join('%.5f' % ticks_to_radians(name, STARTUP_TICKS[name])
                    for name in ARM_JOINTS)
    lines.append('  <group_state name="home" group="arm">')
    for name in ARM_JOINTS:
        lines.append('    <joint name="%s" value="%.5f"/>'
                     % (name, ticks_to_radians(name, STARTUP_TICKS[name])))
    lines.append('  </group_state>')
    lines.append('</robot>')
    return '\n'.join(lines) + '\n', pose


def build_joint_limits():
    lines = ['# Generated by tools/build_moveit_config.py',
             '# Limits converted from the MEASURED servo tick ranges, not from a',
             '# nominal datasheet: joint2 really only spans 125..875 ticks.',
             'joint_limits:']
    for name in ARM_JOINTS:
        low, high = limits_radians(name)
        lines += ['  %s:' % name,
                  '    has_position_limits: true',
                  '    min_position: %.5f' % low,
                  '    max_position: %.5f' % high,
                  '    has_velocity_limits: true',
                  '    max_velocity: %.3f' % MAX_VELOCITY,
                  '    has_acceleration_limits: true',
                  '    max_acceleration: %.3f' % MAX_ACCELERATION]
    return '\n'.join(lines) + '\n'


def build_kinematics():
    lines = ['# Generated by tools/build_moveit_config.py',
             '# This arm is a 4-DOF planar chain plus wrist roll, so the default KDL',
             '# solver has an under-determined problem: it needs more attempts than',
             '# the usual 0.005 s, and it will happily return solutions that are',
             '# reachable but wrong-side. Callers must check the FK residual.',
             'arm:',
             '  kinematics_solver: kdl_kinematics_plugin/KDLKinematicsPlugin',
             '  kinematics_solver_search_resolution: 0.005',
             '  kinematics_solver_timeout: 0.05',
             '  kinematics_solver_attempts: 5']
    return '\n'.join(lines) + '\n'


def build_params_yaml():
    """One params file move_group can consume with --params-file.

    robot_description_kinematics and robot_description_planning are DICTIONARY
    parameters, so they cannot be passed with '-p name:=text' the way the URDF
    string can.  They have to arrive as YAML.
    """
    lines = ['# Generated by tools/build_moveit_config.py',
             '/**:',
             '  ros__parameters:',
             '    planning_pipelines: ["ompl"]',
             '    default_planning_pipeline: "ompl"',
             '    ompl:',
             '      planning_plugins: ["ompl_interface/OMPLPlanner"]',
             '      request_adapters:',
             '        - default_planning_request_adapters/ResolveConstraintFrames',
             '        - default_planning_request_adapters/ValidateWorkspaceBounds',
             '        - default_planning_request_adapters/CheckStartStateBounds',
             '        - default_planning_request_adapters/CheckStartStateCollision',
             '      response_adapters:',
             '        - default_planning_response_adapters/AddTimeOptimalParameterization',
             '        - default_planning_response_adapters/ValidateSolution',
             '    robot_description_kinematics:',
             '      arm:',
             '        kinematics_solver: kdl_kinematics_plugin/KDLKinematicsPlugin',
             '        kinematics_solver_search_resolution: 0.005',
             '        kinematics_solver_timeout: 0.05',
             '        kinematics_solver_attempts: 5',
             '    robot_description_planning:',
             '      joint_limits:']
    for name in ARM_JOINTS:
        low, high = limits_radians(name)
        lines += ['        %s:' % name,
                  '          has_position_limits: true',
                  '          min_position: %.5f' % low,
                  '          max_position: %.5f' % high,
                  '          has_velocity_limits: true',
                  '          max_velocity: %.3f' % MAX_VELOCITY,
                  '          has_acceleration_limits: true',
                  '          max_acceleration: %.3f' % MAX_ACCELERATION]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--out', default=DEFAULT_OUT)
    args = parser.parse_args()

    root = ET.parse(URDF).getroot()
    os.makedirs(args.out, exist_ok=True)

    srdf, pose = build_srdf(root)
    files = {
        'armpi_pro.srdf': srdf,
        'joint_limits.yaml': build_joint_limits(),
        'kinematics.yaml': build_kinematics(),
        'moveit_params.yaml': build_params_yaml(),
    }
    for name, text in files.items():
        path = os.path.join(args.out, name)
        with open(path, 'w', encoding='utf-8') as handle:
            handle.write(text)
        print('%-22s %5d bytes' % (name, len(text)))

    print()
    print('planning group "arm"  : arm_base -> grasping_frame')
    print('home pose (radians)   : %s' % pose)
    print('self-collision pairs  : %d exempted' % len(adjacent_pairs(root)))
    print('joint2 real range     : %.4f .. %.4f rad (125..875 ticks)'
          % (ticks_to_radians('joint2', 125), ticks_to_radians('joint2', 875)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
